def default_filename(m, game="minigolf"):
    """Vorgeschlagener Dateiname beim Teilen: die id plus Endung."""
    fallback = "level" if game == "geodash" else "map"
    return (m.get("id") or fallback) + ext(game)


def export_to(m, path, game="minigolf"):
    """Schreibt genau EINEN Inhalt in seinen Umschlag. Gibt (ok, grund) zurück.

    grund: "" | "invalid" | "swear" | "io".
    """
    if not _valid(m, game):
        return False, "invalid"
    if not swear.all_clean(m.get("name"), m.get("id"), m.get("author")):
        return False, "swear"
    k = kind(game)
    payload = {"format": k["format"], "v": VERSION, "app": "PyGameZ",
               "exported": time.strftime("%Y-%m-%d %H:%M"), k["key"]: dict(m)}
    try:
        folder = os.path.dirname(os.path.abspath(path))
        if folder and not os.path.isdir(folder):
            os.makedirs(folder, exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            json.dump(payload, f, indent=2, ensure_ascii=False)
        return True, ""
    except OSError:
        return False, "io"


def detect_game(raw):
    """Art eines Umschlags anhand seines "format" (oder None)."""
    if isinstance(raw, dict):
        for game, k in KINDS.items():
            if raw.get("format") == k["format"]:
                return game
    return None


def import_from(path, game="minigolf"):
    """Liest einen geteilten Inhalt ein. Gibt (ok, grund, inhalt) zurück.

    Die Art bestimmt der Umschlag ("format"). 'game' ist die Art, die der
    aufrufende Dialog erwartet - passt sie nicht, gibt es "format" (None =
    jede Art annehmen). Eine nackte Map ohne Umschlag geht nur bei Minigolf.
    Der Inhalt wird direkt gespeichert; eine schon vergebene id bekommt
    automatisch ein "-2" (der zurückgegebene Inhalt trägt dann die neue id).
    grund: "" | "io" | "format" | "swear" | "full" | "invalid" | "id".
    """
    try:
        with open(path, "r", encoding="utf-8") as f:
            raw = json.load(f)
    except (OSError, json.JSONDecodeError, ValueError):
        return False, "io", None
    if not isinstance(raw, dict):
        return False, "format", None
    found = detect_game(raw)
    if found is None:
        # Kein bekannter Umschlag: notfalls eine nackte Minigolf-Map.
        if game not in (None, "minigolf"):
            return False, "format", None
        found, m = "minigolf", raw
    else:
        if game is not None and found != game:
            return False, "format", None
        m = raw.get(kind(found)["key"])
    if not isinstance(m, dict):
        return False, "format", None
    k = kind(found)
    m = dict(m)
    m["id"] = slug(m.get("id") or m.get("name") or "")
    m["name"] = (m.get("name") or m["id"] or "").strip()[:MAX_NAME]
    if isinstance(m.get("author"), str):
        m["author"] = m["author"].strip()[:MAX_AUTHOR]
    m = k["normalize"](m) or m
    if not k["validate"](m):
        return False, "format", None
    if not swear.all_clean(m.get("name"), m.get("id"), m.get("author")):
        return False, "swear", None
    if is_full(found):
        return False, "full", None
    m["id"] = unique_id(m["id"], found)
    ok, reason = save_map(m, found)
    return (True, "", m) if ok else (False, reason, None)
