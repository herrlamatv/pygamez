//! replay.rs
//! =========
//! Aufzeichnung und Verwaltung von Spiel-Wiederholungen (aus `replay.py`).
//!
//! Gespeichert wird in `replay.json` im Datenordner (neben `mem.json`), je
//! Spiel eine Liste (neueste zuerst). Aufgezeichnet wird nicht die Eingabe,
//! sondern die Bahn der Objekte im festen Raster (`RATE` Samples je Sekunde).
//! Ein Replay ist ein JSON-Objekt mit `v`, `id`, `game`, `date`, `by`,
//! `title`, `sub`, `rate`, `meta`, optional `layouts` und `scenes`; jede Szene
//! traegt ihre Kopfdaten und unter `f` die Samples.
//!
//! Spiele nutzen `Recorder::scene`, `tick`, `close` und `result`; Bowling,
//! Billard, Pinball, Snake und Tetris dazu `Delta` fuer Aenderungs-Samples.

use std::collections::HashMap;
use std::path::{Path, PathBuf};

use serde_json::{json, Map, Value};

/// Samples je Sekunde.
pub const RATE: f64 = 30.0;
/// Abstand zweier Samples.
pub const STEP: f64 = 1.0 / RATE;
/// Format-Version.
pub const VERSION: i64 = 1;
/// Spiele mit Aufzeichnung (Reihenfolge = Reiter im Replay-Screen).
pub const GAMES: [&str; 6] = ["minigolf", "bowling", "billiard", "pinball", "snake", "tetris"];
/// Endung einer geteilten Aufnahme.
pub const EXT: &str = ".lamapgzreplay";
/// Kennung im Dateikopf.
pub const FORMAT: &str = "pygamez.replay";
/// Hoechstens so viele gespeicherte Replays je Spiel.
pub const MAX_PER_GAME: usize = 20;
/// Sicherheitsnetz gegen Endlos-Partien.
pub const MAX_SAMPLES: usize = 60000;
/// ... und gegen sehr volle Bilder.
pub const MAX_VALUES: usize = 420000;

fn path() -> PathBuf {
    crate::store::data_dir().join("replay.json")
}

fn now(fmt: &str) -> String {
    chrono::Local::now().format(fmt).to_string()
}

fn read_raw() -> Map<String, Value> {
    std::fs::read_to_string(path())
        .ok()
        .and_then(|s| serde_json::from_str::<Value>(&s).ok())
        .and_then(|v| v.as_object().cloned())
        .unwrap_or_default()
}

fn write_raw(data: &Map<String, Value>) -> bool {
    let stamp = match data.get("_generated").and_then(|v| v.as_str()) {
        Some(s) if !s.is_empty() => s.to_string(),
        _ => format!("generated by PyGameZ at {} (YYYY-MM-DD HH:MM:SS)", now("%Y-%m-%d %H:%M:%S")),
    };
    let mut out = Map::new();
    out.insert("_generated".into(), Value::String(stamp));
    for key in GAMES {
        if let Some(Value::Array(items)) = data.get(key) {
            if !items.is_empty() {
                out.insert(key.into(), Value::Array(items.clone()));
            }
        }
    }
    match serde_json::to_string(&Value::Object(out)) {
        Ok(text) => std::fs::write(path(), text).is_ok(),
        Err(_) => false,
    }
}

/// Grobpruefung eines geladenen Replays.
pub fn valid(rep: &Value) -> bool {
    let Some(o) = rep.as_object() else { return false };
    matches!(o.get("scenes"), Some(Value::Array(s)) if !s.is_empty())
        && o.get("id").is_some_and(|v| v.is_string())
        && o.get("game").and_then(|v| v.as_str()).is_some_and(|g| GAMES.contains(&g))
}

/// Alle gespeicherten Replays eines Spiels (neueste zuerst).
pub fn load_game(game: &str) -> Vec<Value> {
    match read_raw().get(game) {
        Some(Value::Array(items)) => items.iter().filter(|r| valid(r)).cloned().collect(),
        _ => Vec::new(),
    }
}

/// Anzahl gespeicherter Replays eines Spiels.
pub fn count(game: &str) -> usize {
    load_game(game).len()
}

/// Archiv dieses Spiels voll?
pub fn is_full(game: &str) -> bool {
    count(game) >= MAX_PER_GAME
}

/// Speichert ein Replay dauerhaft -> (ok, grund).
pub fn save_replay(rep: &Value) -> (bool, &'static str) {
    if !valid(rep) {
        return (false, "invalid");
    }
    let game = rep["game"].as_str().unwrap_or_default().to_string();
    let id = rep["id"].clone();
    let mut data = read_raw();
    let mut items: Vec<Value> = match data.get(&game) {
        Some(Value::Array(a)) => a.iter().filter(|r| valid(r) && r.get("id") != Some(&id)).cloned().collect(),
        _ => Vec::new(),
    };
    if items.len() >= MAX_PER_GAME {
        return (false, "full");
    }
    items.insert(0, rep.clone());
    data.insert(game, Value::Array(items));
    if write_raw(&data) {
        (true, "")
    } else {
        (false, "io")
    }
}

/// Loescht ein gespeichertes Replay.
pub fn delete_replay(game: &str, rep_id: &str) -> bool {
    let mut data = read_raw();
    let Some(Value::Array(items)) = data.get(game) else { return false };
    let keep: Vec<Value> = items.iter().filter(|r| r.get("id").and_then(|v| v.as_str()) != Some(rep_id)).cloned().collect();
    if keep.len() == items.len() {
        return false;
    }
    data.insert(game.into(), Value::Array(keep));
    write_raw(&data)
}

/// Liegt ein Replay mit dieser id schon im Archiv?
pub fn is_saved(game: &str, rep_id: &str) -> bool {
    load_game(game).iter().any(|r| r.get("id").and_then(|v| v.as_str()) == Some(rep_id))
}

/// Freie id im Archiv ("-2", "-3" ... angehaengt).
pub fn unique_id(wanted: &str, game: &str) -> String {
    let wanted = if wanted.is_empty() { if game.is_empty() { "replay" } else { game } } else { wanted };
    if !is_saved(game, wanted) {
        return wanted.to_string();
    }
    for n in 2..1000 {
        let cand = format!("{wanted}-{n}");
        if !is_saved(game, &cand) {
            return cand;
        }
    }
    format!("{wanted}-{}", now("%H%M%S"))
}

/// Vorgeschlagener Dateiname beim Teilen.
pub fn default_filename(rep: &Value) -> String {
    let base = rep.get("id").and_then(|v| v.as_str()).or_else(|| rep.get("game").and_then(|v| v.as_str())).unwrap_or("replay");
    let keep = |c: char| c.is_ascii_alphanumeric() || c == '-' || c == '_';
    let mut b: String = base.chars().map(|c| if keep(c) { c } else { '-' }).take(60).collect();
    if b.is_empty() {
        b = "replay".into();
    }
    b + EXT
}

/// Schreibt genau ein Replay in seinen Umschlag -> (ok, grund).
pub fn export_to(rep: &Value, target: &Path) -> (bool, &'static str) {
    if !valid(rep) {
        return (false, "invalid");
    }
    let payload = json!({"format": FORMAT, "v": VERSION, "app": "PyGameZ", "exported": now("%Y-%m-%d %H:%M"), "replay": rep});
    if let Some(dir) = target.parent() {
        if !dir.as_os_str().is_empty() && !dir.is_dir() && std::fs::create_dir_all(dir).is_err() {
            return (false, "io");
        }
    }
    match serde_json::to_string(&payload) {
        Ok(text) if std::fs::write(target, &text).is_ok() => (true, ""),
        _ => (false, "io"),
    }
}

/// Liest eine geteilte Aufnahme -> (ok, grund, replay).
pub fn read_file(source: &Path) -> (bool, &'static str, Option<Value>) {
    let Some(raw) = std::fs::read_to_string(source).ok().and_then(|s| serde_json::from_str::<Value>(&s).ok()) else {
        return (false, "io", None);
    };
    if !raw.is_object() {
        return (false, "format", None);
    }
    let rep = if raw.get("format").and_then(|v| v.as_str()) == Some(FORMAT) { raw.get("replay").cloned().unwrap_or(Value::Null) } else { raw };
    if !valid(&rep) {
        return (false, "format", None);
    }
    (true, "", Some(rep))
}

/// Liest eine geteilte Aufnahme ein und legt sie ins Archiv.
pub fn import_from(source: &Path, game: Option<&str>) -> (bool, &'static str, Option<Value>) {
    let (ok, why, rep) = read_file(source);
    let Some(mut rep) = rep.filter(|_| ok) else { return (false, why, None) };
    let found = rep["game"].as_str().unwrap_or_default().to_string();
    if game.is_some_and(|g| g != found) {
        return (false, "game", None);
    }
    if is_full(&found) {
        return (false, "full", None);
    }
    let id = rep["id"].as_str().unwrap_or_default().to_string();
    if is_saved(&found, &id) {
        return (false, "dup", Some(rep));
    }
    rep["id"] = Value::String(unique_id(&id, &found));
    rep["src"] = Value::String("file".into());
    let (ok, why) = save_replay(&rep);
    if ok {
        (true, "", Some(rep))
    } else {
        (false, why, None)
    }
}

/// Anzahl Samples einer Szene (flache zaehlen paarweise).
pub fn scene_len(scene: &Value) -> usize {
    let Some(Value::Array(f)) = scene.get("f") else { return 0 };
    if scene.get("flat").and_then(|v| v.as_bool()).unwrap_or(false) {
        f.len() / 2
    } else {
        f.len()
    }
}

/// Spieldauer eines Replays in Sekunden.
pub fn duration(rep: &Value) -> f64 {
    let rate = rep.get("rate").and_then(|v| v.as_f64()).filter(|r| *r != 0.0).unwrap_or(RATE);
    let total: usize = rep.get("scenes").and_then(|v| v.as_array()).map(|s| s.iter().map(scene_len).sum()).unwrap_or(0);
    total as f64 / rate
}

/// Sekunden -> "1:05".
pub fn format_duration(seconds: f64) -> String {
    let s = 0.max((seconds + 0.5) as i64);
    format!("{}:{:02}", s / 60, s % 60)
}

/// `Delta` - Samples, die nur Aenderungen enthalten.
#[derive(Default, Clone)]
pub struct Delta {
    prev: HashMap<i64, Vec<Value>>,
}

impl Delta {
    /// `Delta()`
    pub fn new() -> Delta {
        Delta::default()
    }

    /// Zu Beginn einer Szene: alles vergessen.
    pub fn reset(&mut self) {
        self.prev.clear();
    }

    /// True, wenn sich `state` seit dem letzten Mal geaendert hat.
    pub fn push(&mut self, key: i64, state: &[Value]) -> bool {
        if self.prev.get(&key).is_some_and(|p| p.as_slice() == state) {
            return false;
        }
        self.prev.insert(key, state.to_vec());
        true
    }
}

/// `Recorder` - sammelt die Bahnkurven einer Partie.
pub struct Recorder {
    game: String,
    meta: Map<String, Value>,
    layouts: Vec<Value>,
    scenes: Vec<Map<String, Value>>,
    samples: usize,
    values: usize,
    /// Obergrenze erreicht.
    pub full: bool,
    dead: bool,
    open: bool,
    acc: f64,
}

impl Recorder {
    /// `Recorder(game, meta)`
    pub fn new(game: &str, meta: Map<String, Value>) -> Recorder {
        Recorder { game: game.into(), meta, layouts: Vec::new(), scenes: Vec::new(), samples: 0, values: 0, full: false, dead: false, open: false, acc: 0.0 }
    }

    /// Legt eine Kulisse ab und gibt ihren Index zurueck (ohne Dubletten).
    pub fn layout(&mut self, data: Value) -> usize {
        if self.dead {
            return 0;
        }
        if let Some(i) = self.layouts.iter().position(|k| *k == data) {
            return i;
        }
        self.layouts.push(data);
        self.layouts.len() - 1
    }

    /// Beginnt eine Sequenz.
    pub fn scene(&mut self, flat: bool, info: Map<String, Value>) {
        if self.dead || self.full {
            return;
        }
        let mut sc = info;
        sc.insert("flat".into(), Value::Bool(flat));
        sc.insert("f".into(), Value::Array(Vec::new()));
        self.scenes.push(sc);
        self.open = true;
        self.acc = STEP;
    }

    /// Kopfdaten in die laufende Sequenz nachtragen.
    pub fn set(&mut self, info: Map<String, Value>) {
        if self.open {
            if let Some(sc) = self.scenes.last_mut() {
                sc.extend(info);
            }
        }
    }

    /// Kopfdaten in die zuletzt begonnene Sequenz nachtragen.
    pub fn set_last(&mut self, info: Map<String, Value>) {
        if !self.dead {
            if let Some(sc) = self.scenes.last_mut() {
                sc.extend(info);
            }
        }
    }

    /// Samples im Raster `RATE` nehmen (je Bild einmal aufrufen).
    pub fn tick(&mut self, dt: f64, mut sample_fn: impl FnMut() -> Option<Vec<Value>>) {
        if self.dead || self.full || !self.open {
            return;
        }
        self.acc += dt;
        while self.acc >= STEP {
            self.acc -= STEP;
            let v = sample_fn();
            self.emit(v);
        }
    }

    fn emit(&mut self, values: Option<Vec<Value>>) {
        let Some(values) = values else { return };
        if self.full || !self.open {
            return;
        }
        let n = values.len();
        let Some(sc) = self.scenes.last_mut() else { return };
        let flat = sc.get("flat").and_then(|v| v.as_bool()).unwrap_or(false);
        if let Some(Value::Array(f)) = sc.get_mut("f") {
            if flat {
                f.extend(values);
            } else {
                f.push(Value::Array(values));
            }
        }
        self.samples += 1;
        self.values += n + 1;
        if self.samples > MAX_SAMPLES || self.values > MAX_VALUES {
            self.full = true;
            self.open = false;
        }
    }

    /// Beendet die laufende Sequenz (mit einem letzten Sample).
    pub fn close(&mut self, last: Option<Vec<Value>>, info: Map<String, Value>) {
        if self.dead || !self.open {
            return;
        }
        if last.is_some() {
            self.emit(last);
        }
        if self.open {
            if let Some(sc) = self.scenes.last_mut() {
                sc.extend(info);
            }
        }
        self.open = false;
    }

    /// Ist gerade eine Sequenz offen?
    pub fn is_open(&self) -> bool {
        self.open
    }

    /// `bool(rec.scenes)` - gibt es schon Sequenzen?
    pub fn has_scenes(&self) -> bool {
        !self.scenes.is_empty()
    }

    /// `len(rec.scenes)`
    pub fn scene_count(&self) -> usize {
        self.scenes.len()
    }

    /// Sequenzen verwerfen, deren Kopfdaten alle Vorgaben erfuellen.
    pub fn drop_where(&mut self, matches: &Map<String, Value>) {
        if self.dead {
            return;
        }
        let mut keep = Vec::new();
        for sc in std::mem::take(&mut self.scenes) {
            if matches.iter().all(|(k, v)| sc.get(k) == Some(v)) {
                self.samples = self.samples.saturating_sub(scene_len(&Value::Object(sc.clone())));
                continue;
            }
            keep.push(sc);
        }
        self.scenes = keep;
        self.open = false;
    }

    /// Das fertige Replay (oder `None`, wenn nichts brauchbar ist).
    pub fn result(&mut self, title: &str, sub: &str, meta: Map<String, Value>) -> Option<Value> {
        if self.dead {
            return None;
        }
        let scenes: Vec<Value> = self.scenes.iter().map(|s| Value::Object(s.clone())).filter(|s| scene_len(s) > 0).collect();
        if scenes.is_empty() {
            return None;
        }
        self.meta.extend(meta);
        if self.full {
            self.meta.insert("capped".into(), Value::Bool(true));
        }
        let mut rep = Map::new();
        rep.insert("v".into(), json!(VERSION));
        rep.insert("id".into(), json!(format!("{}-{}-{}", self.game, now("%Y%m%d%H%M%S"), scenes.len())));
        rep.insert("game".into(), json!(self.game));
        rep.insert("date".into(), json!(now("%Y-%m-%d %H:%M")));
        rep.insert("by".into(), json!(crate::profiles::name_of(None)));
        rep.insert("title".into(), json!(title));
        rep.insert("sub".into(), json!(sub));
        rep.insert("rate".into(), json!(RATE as i64));
        rep.insert("meta".into(), Value::Object(self.meta.clone()));
        rep.insert("scenes".into(), Value::Array(scenes));
        if !self.layouts.is_empty() {
            rep.insert("layouts".into(), Value::Array(self.layouts.clone()));
        }
        Some(Value::Object(rep))
    }
}

/// Ein Recorder - oder `None`, wenn Replays abgeschaltet sind.
pub fn recorder(game: &str, enabled: bool, meta: Map<String, Value>) -> Option<Recorder> {
    if !GAMES.contains(&game) || !enabled {
        return None;
    }
    Some(Recorder::new(game, meta))
}

/// Python-`round(x, n)` fuer Replay-Zahlen (als JSON-Kommazahl).
pub fn rnd(x: f64, n: usize) -> Value {
    let v: f64 = format!("{:.*}", n, x).parse().unwrap_or(x);
    json!(v)
}
