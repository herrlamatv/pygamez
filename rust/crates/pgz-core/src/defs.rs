//! defs.rs
//! =======
//! **Erzeugte Datei - nicht von Hand aendern.**
//!
//! Quelle: `rust/tools/export_defs.py` liest `games/__init__.py`,
//! `ui.GAME_COLORS` und `achievements.py` der Python-Fassung aus. So
//! kennen beide Fassungen dieselben Spiele, Akzentfarben und Erfolge -
//! auch die, deren Spiel in Rust noch nicht portiert ist (sonst
//! verschoebe sich die Erfolgs-Gesamtzahl und damit jeder Fortschritt).
//!
//! Neu erzeugen:
//! ```text
//! .venv/Scripts/python.exe rust/tools/export_defs.py
//! ```

/// Eine Farbe als `(rot, gruen, blau)`.
///
/// Die ganze Sammlung rechnet mit 8-Bit-Kanaelen; erst beim Zeichnen
/// wird daraus eine macroquad-Farbe (`ui::col`).
pub type Rgb = (u8, u8, u8);

/// Ein Spiel der Sammlung, so wie die Python-Fassung es kennt.
///
/// `key` ist der Highscore-Schluessel (auch der Name des
/// Statistik-Eintrags), `class_name` der Klassenname aus der
/// Python-Fassung (Schluessel in `ui.GAME_COLORS`), `color` die
/// Akzentfarbe des Spiels und `name` der Anzeigename.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct GameDef {
    pub key: &'static str,
    pub class_name: &'static str,
    pub color: &'static str,
    pub name: &'static str,
}

