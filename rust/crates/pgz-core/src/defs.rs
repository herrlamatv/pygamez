/// Effekt-Schalter eines UI-Designs (Gegenstueck zu `ui._*_FX`).
///
/// Nicht jedes Design kennt jeden Schalter - fehlende stehen hier
/// auf dem ruhigen Standardwert bzw. `None`.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Fx {
    /// Sternenfeld zeichnen, mit Helligkeit und Anzahl.
    pub stars: bool,
    pub star_bright: f64,
    pub star_count: Option<i32>,
    /// Aurora-Lichter und Sternschnuppen.
    pub aurora: bool,
    pub shooting: bool,
    /// Saturn und Schwarzes Loch (UI v4.1).
    pub celestial: bool,
    /// Zickzack-Kachelmuster als Hintergrund: `(Haupt-, Nebenfarbe)`.
    /// (Haupt-, Nebenfarbe)
    pub pattern: Option<(Rgb, Rgb)>,
    /// Staerke der Vignette (0 = aus).
    pub vignette: u8,
    /// Titel mit Schein bzw. Verlaufstext.
    pub title_glow: bool,
    pub title_grad: bool,
    /// Buttons mit Aussen-Schein bzw. Pfeil.
    pub btn_glow: bool,
    pub btn_arrow: bool,
    /// Funken-Partikel bei Klicks.
    pub sparks: bool,
    /// Scanlinie beim Bildwechsel, und wie lange der Wechsel dauert.
    pub scanline: bool,
    pub trans_dur: f64,
    /// Eckenrundungen und Schlagschatten.
    pub panel_radius: i32,
    pub btn_radius: i32,
    pub shadow_alpha: u8,
    /// Wie stark das Logo im Menue schwebt.
    pub menu_bob: i32,
    /// Eigener Zeichenpfad des Designs ("v42", "v2", "v1" oder "").
    pub style: &'static str,
    /// Glas-Panels (UI v4.2): Deckkraft.
    pub glass_alpha: Option<u8>,
    /// Filmkorn (UI v4.2): Staerke.
    pub grain: Option<i32>,
    /// Drei-Farben-Verlauf fuer Titel und Linien.
    pub grad3: Option<[Rgb; 3]>,
    /// Farbwolken des Hintergrunds (UI v4.2).
    pub mesh: &'static [MeshBlob],
    pub mesh_drift: Option<(f64, f64)>,
    /// Logo-Effekte der aelteren Designs.
    pub logo_glow: bool,
    pub logo_halo: bool,
    pub menu_orbit: bool,
}

