# -*- coding: utf-8 -*-
"""Erzeugt `rustgame-mixer/src/filter.rs` aus SDLs Filtertabelle.

SDLs `SDL_audio_resampler_filter.h` ist selbst erzeugt ("DO NOT EDIT,
THIS FILE WAS GENERATED BY build-scripts/gen_audio_resampler_filter.c").
Die Tabelle **nachzurechnen** hiesse, Kaiser-Fenster und Bessel-Funktion
in Gleitkomma genau so zu treffen wie SDLs Generator - eine Quelle fuer
Abweichungen im letzten Bit, und zwar in genau der Zahl, die hinterher
jeden Abtastwert multipliziert.

Deshalb werden die Werte **uebertragen**, nicht hergeleitet: dasselbe
Vorgehen wie bei `draw.c` und `alphablit.c`.

Aufruf:

    python tools/gen_resampler_filter.py
"""
import io
import os
import re

HIER = os.path.dirname(os.path.abspath(__file__))
QUELLE = os.path.join(HIER, "vorlage", "SDL_audio_resampler_filter.h")
ZIEL = os.path.join(HIER, "..", "crates", "rustgame-mixer", "src", "filter.rs")


def tabelle(text, name):
    """Die Werte eines `static const float <name>[...] = { ... };`."""
    m = re.search(r"static const float " + name + r"\[[^\]]*\] = \{(.*?)\};",
                  text, re.S)
    if not m:
        raise SystemExit("Tabelle %s nicht gefunden" % name)
    werte = re.findall(r"(-?\d+\.\d+)f", m.group(1))
    if not werte:
        raise SystemExit("Tabelle %s ist leer" % name)
    return werte


def schreiben(werte, name, aus):
    aus.append("pub static %s: [f32; %d] = [" % (name, len(werte)))
    for i in range(0, len(werte), 6):
        aus.append("    " + " ".join("%s," % w for w in werte[i:i + 6]))
    aus.append("];")
    aus.append("")


def main():
    text = io.open(QUELLE, encoding="utf-8").read()
    f = tabelle(text, "ResamplerFilter")
    d = tabelle(text, "ResamplerFilterDifference")
    if len(f) != len(d):
        raise SystemExit("Die beiden Tabellen sind verschieden lang")

    aus = [
        "//! Die Filtertabelle von SDLs Umrechner - **erzeugt**, nicht",
        "//! von Hand gepflegt.",
        "//!",
        "//! Quelle: `SDL_audio_resampler_filter.h` aus SDL 2.32.10, uebertragen",
        "//! von `tools/gen_resampler_filter.py`. Nicht aendern - beim naechsten",
        "//! Lauf des Werkzeugs waere die Aenderung wieder fort.",
        "//!",
        "//! Warum uebertragen und nicht nachgerechnet: die Werte entstehen aus",
        "//! einem Kaiser-Fenster mit einer Bessel-Funktion, und jede",
        "//! Abweichung im letzten Bit multipliziert hinterher **jeden**",
        "//! Abtastwert. Dieselbe Ueberlegung wie bei `draw.c`.",
        "",
        "// Die Ziffern stehen so in SDLs Datei, und sie bleiben so stehen:",
        "// clippy haette gern weniger, weil `f32` sie nicht alle traegt -",
        "// aber genau diese Schreibweise **ist** die Quelle, und sie zu",
        "// kuerzen hiesse, die Uebertragung stillschweigend zu veraendern.",
        "#![allow(clippy::excessive_precision)]",
        "",
        "/// `RESAMPLER_ZERO_CROSSINGS` - fuenf Nulldurchgaenge je Fluegel.",
        "pub const NULLDURCHGAENGE: usize = 5;",
        "",
        "/// `RESAMPLER_SAMPLES_PER_ZERO_CROSSING` - `1 << (16 / 2 + 1)`.",
        "pub const JE_NULLDURCHGANG: usize = 512;",
        "",
        "/// `RESAMPLER_FILTER_SIZE` - `JE_NULLDURCHGANG * NULLDURCHGAENGE + 1`.",
        "pub const FILTERLAENGE: usize = JE_NULLDURCHGANG * NULLDURCHGAENGE + 1;",
        "",
    ]
    schreiben(f, "FILTER", aus)
    schreiben(d, "FILTER_UNTERSCHIED", aus)

    io.open(ZIEL, "w", encoding="utf-8", newline="\n").write("\n".join(aus))
    print("filter.rs: %d Werte je Tabelle" % len(f))


if __name__ == "__main__":
    main()
